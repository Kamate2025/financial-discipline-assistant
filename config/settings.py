def env_flag(name, default="false"):
    """Read a boolean setting from an environment variable."""
    return os.environ.get(name, default).strip().lower() in {"true", "1", "yes", "on", "t"}


def read_env_file(path):
    """Load environment variables from a .env file using only the standard library.

    Existing environment variables are never overwritten, so deployment
    environments can provide values directly.
    """
    if not path.exists():
        return
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = value


# Load project-root .env for local development before settings are read.
